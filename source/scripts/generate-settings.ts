import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SETTINGS_CATALOG } from '../shared/settings.ts';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const q=(s:string)=>JSON.stringify(s).replace(/\\u2028/g,' ');
const lit=(v:unknown)=>typeof v==='string'?q(v):typeof v==='number'?`${v}d`:String(v);
const code=`// Generated by scripts/generate-settings.ts. Edit shared/settings.ts instead.
using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text.RegularExpressions;
namespace LivingLosSantosV2 {
public sealed class SettingDefinition {
 public string Key, Label, Group, Kind, Tooltip, Consumer;
 public object Default;
 public double Min, Max, Step;
 public string[] Options;
}
public static class SettingsCatalog {
 public static readonly SettingDefinition[] All = new SettingDefinition[] {
${SETTINGS_CATALOG.map(s=>`  new SettingDefinition { Key=${q(s.key)},Label=${q(s.label)},Group=${q(s.group)},Kind=${q(s.type)},Default=${lit(s.default)},Min=${s.min??0}d,Max=${s.max??0}d,Step=${s.step??1}d,Options=new string[]{${(s.options??[]).map(q).join(',')}},Tooltip=${q(s.tooltip)},Consumer=${q(s.consumer)} }`).join(',\n')}
 };
 public static Dictionary<string,object> Defaults() {var result=new Dictionary<string,object>();foreach(var s in All)result.Add(s.Key,s.Default);return result;}
 public static Dictionary<string,object> Validate(Dictionary<string,object> patch) {
  if(patch==null||patch.Count==0||patch.Count>All.Length) throw new InvalidOperationException("Invalid settings patch.");
  var output=new Dictionary<string,object>();
  foreach(var pair in patch) {
   SettingDefinition s=null;foreach(var item in All)if(item.Key==pair.Key){s=item;break;}
   if(s==null)throw new InvalidOperationException("Unknown setting.");
   if(s.Kind=="boolean") {if(!(pair.Value is bool))throw new InvalidOperationException("Invalid boolean setting.");}
   else if(s.Kind=="number") {
    if(!(pair.Value is int)&&!(pair.Value is long)&&!(pair.Value is double)&&!(pair.Value is decimal))throw new InvalidOperationException("Invalid numeric setting.");
    double n=Convert.ToDouble(pair.Value,CultureInfo.InvariantCulture);
    bool integral=s.Min==Math.Truncate(s.Min)&&s.Max==Math.Truncate(s.Max)&&s.Step==Math.Truncate(s.Step);
    if(Double.IsNaN(n)||Double.IsInfinity(n)||n<s.Min||n>s.Max||(integral&&n!=Math.Truncate(n)))throw new InvalidOperationException("Out-of-range setting.");
   } else {
    var text=pair.Value as string;
    if(String.IsNullOrWhiteSpace(text)||text.Length>128)throw new InvalidOperationException("Invalid text setting.");
    foreach(char c in text)if(Char.IsControl(c)||c=='~'||c=='<'||c=='>')throw new InvalidOperationException("Unsafe text setting.");
    if(s.Options.Length>0&&Array.IndexOf(s.Options,text)<0)throw new InvalidOperationException("Unsupported setting option.");
    if(s.Key=="conversation.language"&&text.Length>40)throw new InvalidOperationException("Language name too long.");
    if(s.Key.StartsWith("ai.")&&s.Key.EndsWith("Model")&&!Regex.IsMatch(text,@"^[a-zA-Z0-9][a-zA-Z0-9._-]{1,79}$"))throw new InvalidOperationException("Invalid model identifier.");
    if(s.Key.StartsWith("controls.")&&s.Key.EndsWith("Key")) {
     if(!Regex.IsMatch(text,@"^(F[1-9]|F1[0-2]|[A-Z]|NumPad[0-9]|Home|End|Insert|Delete|PageUp|PageDown)$")||text=="F4"||text=="F8")throw new InvalidOperationException("Reserved or unsupported keyboard binding.");
    }
   }
   output.Add(pair.Key,pair.Value);
  }
  return output;
 }
}
}
`;
const output=path.join(root,'game-client','SettingsCatalog.Generated.cs');
if(process.argv.includes('--check')) {if(!fs.existsSync(output)||fs.readFileSync(output,'utf8').replace(/\r\n/g,'\n')!==code)throw new Error('Generated C# settings are stale. Run scripts/generate-settings.ts.');}
else fs.writeFileSync(output,code,'utf8');
console.log(JSON.stringify({settings:SETTINGS_CATALOG.length,groups:[...new Set(SETTINGS_CATALOG.map(s=>s.group))],output,checked:process.argv.includes('--check')}));
